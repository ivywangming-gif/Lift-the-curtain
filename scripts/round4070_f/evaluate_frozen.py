"""Replay Phase-A checkpoints and evaluate F without fitting any parameter.

F episodes are assigned to the Phase-A fold that held out the entire matching
physical family. UNKNOWN receives predictions but is excluded from all metrics.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path
import sys

import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from train_models import Temporal, csvwrite, dump, metrics, resample

OUT = ROOT / "outputs/round4070_learning_traversability"
REPORT = ROOT / "research/round4070_learning_traversability"
METHODS = ("Logistic", "GRU", "TCN", "ResidualGRU", "M2")


def load(path):
    return json.loads(Path(path).read_text(encoding="utf-8-sig"))


def read_csv(path):
    with Path(path).open(encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def family(episode):
    return episode.get("condition_family_group", episode.get("condition_id", episode["group_id"]))


def data(episode, feature_names):
    path = Path(episode["npz_path"])
    if not path.is_absolute():
        path = ROOT / path
    d = np.load(path, allow_pickle=False)
    names = list(d["feature_names"].astype(str))
    keep = [names.index(n) for n in feature_names]
    assert [names[i] for i in keep] == feature_names
    return d["seq"].astype("float32")[:, keep], d["time"]


def apply_response(x, t, weights):
    """Inference-only copy of the verified training transformation."""
    target, state, cmd = weights["targets"], weights["state"], weights["cmd"]
    idx = np.maximum(0, np.searchsorted(t, t-.4, side="right")-1)
    inputs = np.concatenate([x[idx][:, state], x[:, cmd]], 1)
    z = np.column_stack([(inputs-weights["mu"])/weights["sd"], np.ones(len(x))])
    r = x[:, target] - z @ weights["w"]
    r[~(t-t[0] >= .4)] = 0
    return np.concatenate([x, r], 1).astype("float32")


def predict(episodes, model_root, fold, method, seed, sequence_length=48):
    path = model_root / f"{fold}_{method}_{seed}.pt"
    # Checkpoints are locally generated by this task, not third-party pickle.
    checkpoint = torch.load(path, map_location="cpu", weights_only=False)
    response_path = model_root / f"{fold}_normal_response.npz"
    weights = np.load(response_path, allow_pickle=False)
    xs = []
    for episode in episodes:
        x, t = data(episode, checkpoint["feature_names"])
        if method in {"ResidualGRU", "M2"}:
            x = apply_response(x, t, weights)
        x = resample(x, n=sequence_length, times=t)
        x = np.clip((x-checkpoint["mean"])/checkpoint["scale"], -10, 10).astype("float32")
        if method == "ResidualGRU":
            x = x[:, checkpoint["arm"]]
        xs.append(x)
    x = np.stack(xs)
    model = Temporal(checkpoint["kind"], x.shape[2], checkpoint["arm"], checkpoint["body"], sequence_length)
    model.load_state_dict(checkpoint["state_dict"], strict=True)
    model.eval()
    with torch.inference_mode():
        p = torch.sigmoid(model(torch.tensor(x))).numpy()
    return p, {"checkpoint": str(path.relative_to(ROOT)), "checkpoint_sha256": sha(path), "response_sha256": sha(response_path), "supervised_train_ids": checkpoint["train_ids"]}


def replay(model_root, e_manifest, output):
    config = load(model_root / "frozen_config.json")
    episodes = {e["trial_id"]: e for e in e_manifest["episodes"]}
    expected = {(r["fold"], r["method"], int(r["seed"]), r["trial_id"]): float(r["p"]) for r in read_csv(model_root / "predictions.csv")}
    rows = []
    for fold in config["folds"]:
        if fold["name"] not in {"family_fold_0", "family_fold_1"}:
            continue
        selected = [episodes[i] for i in fold["test"]]
        for method in METHODS:
            for seed in config["seeds"]:
                probabilities, provenance = predict(selected, model_root, fold["name"], method, seed, config["sequence_length"])
                original = np.array([expected[(fold["name"], method, seed, e["trial_id"])] for e in selected])
                max_error = float(np.max(np.abs(probabilities-original)))
                assert max_error <= 1e-6, (fold["name"], method, seed, max_error)
                rows.append({"fold": fold["name"], "method": method, "seed": seed, "n": len(selected), "max_absolute_probability_error": max_error, "passed": True, **{k: v for k, v in provenance.items() if k != "supervised_train_ids"}})
    report = {"status": "PASS", "tolerance": 1e-6, "prediction_count": sum(r["n"] for r in rows), "model_count": len(rows), "max_absolute_probability_error": max(r["max_absolute_probability_error"] for r in rows), "frozen_config_sha256": sha(model_root / "frozen_config.json"), "rows": rows}
    dump(output / "E_HOLDOUT_REPLAY_VALIDATION.json", report)
    return report


def choose_fold(episode, folds, e_episodes):
    target = family(episode)
    candidates = []
    for fold in folds:
        if fold["name"] not in {"family_fold_0", "family_fold_1"}:
            continue
        held_out = {family(e_episodes[i]) for i in fold["test"]}
        train_families = {family(e_episodes[i]) for i in fold["train"]}
        if target in held_out:
            assert target not in train_families
            candidates.append(fold["name"])
    assert len(candidates) == 1, (episode["trial_id"], target, candidates)
    return candidates[0]


def shift_type(episode):
    plan = episode["physics_configuration_audit_only"]
    length = float(plan.get("curtain_length", plan.get("curtain_length_m", 2.0)))
    if abs(length-2.0) > 1e-8:
        return "NEW_LENGTH_AND_NEW_SEED"
    stage = str(episode.get("source_stage", "")).lower()
    if "posture" in stage or "posture" in episode["trial_id"].lower():
        return "NEW_POSTURE_AND_NEW_SEED"
    return "NEW_SEED_SAME_PHYSICAL_CONFIGURATION"


def decision(p, low, high):
    return "PASSABLE" if p >= high else "BLOCKED" if p < low else "UNCERTAIN"


def baseline_metrics(episodes, method):
    selected = [e for e in episodes if e["y"] >= 0 and not e["is_control"]]
    # Only classification metrics; rules do not provide calibrated probabilities.
    y = np.array([e["y"] for e in selected])
    p = np.array([{"PASSABLE": 1., "BLOCKED": 0., "UNCERTAIN": .5}[e["engineering_decisions"][method]] for e in selected])
    result = metrics(y, p, .25, .75)
    result["brier"] = None
    return result


def evaluate_f(model_root, e_manifest, f_manifest, output):
    config = load(model_root / "frozen_config.json")
    frozen_metrics = {(r["fold"], r["method"], int(r["seed"]), r["mode"]): r for r in read_csv(model_root / "metrics.csv")}
    e_episodes = {e["trial_id"]: e for e in e_manifest["episodes"]}
    supplements = [e for e in f_manifest["episodes"] if e["campaign"] == "4070-F"]
    assert supplements, "No actual F episodes: evaluation not claimed"
    assignments = {e["trial_id"]: choose_fold(e, config["folds"], e_episodes) for e in supplements}
    provenance, predictions = [], []
    for fold in sorted(set(assignments.values())):
        selected = [e for e in supplements if assignments[e["trial_id"]] == fold]
        for method in METHODS:
            for seed in config["seeds"]:
                p, source = predict(selected, model_root, fold, method, seed, config["sequence_length"])
                assert not set(source["supervised_train_ids"]) & {e["trial_id"] for e in supplements}
                provenance.append({"fold": fold, "method": method, "seed": seed, **source})
                for i, e in enumerate(selected):
                    thresholds = frozen_metrics[(fold, method, seed, "validation_zero_fp")]
                    predictions.append({"trial_id": e["trial_id"], "fold": fold, "method": method, "seed": seed, "label": e["label"], "y": e["y"], "side": e["side"], "group_id": e["group_id"], "family": family(e), "shift_type": shift_type(e), "source_stage": e["source_stage"], "p": float(p[i]), "forced": decision(p[i], .5, .5), "selective": decision(p[i], .2, .8), "validation_zero_fp": decision(p[i], float(thresholds["low"]), float(thresholds["high"])), "validation_low": float(thresholds["low"]), "validation_high": float(thresholds["high"]), "supervised_evaluation_eligible": e["y"] >= 0 and not e["is_control"]})
    rows = []
    scopes = ["all"] + sorted({shift_type(e) for e in supplements})
    for scope in scopes:
        eps = [e for e in supplements if scope == "all" or shift_type(e) == scope]
        for method in METHODS:
            for seed in config["seeds"]:
                full = [r for r in predictions if r["method"] == method and r["seed"] == seed and (scope == "all" or r["shift_type"] == scope)]
                selected = [r for r in full if r["supervised_evaluation_eligible"]]
                for mode in ("forced", "selective", "validation_zero_fp"):
                    y = np.array([r["y"] for r in selected])
                    p = np.array([r["p"] for r in selected])
                    mapped = np.array([{"PASSABLE": 1., "BLOCKED": 0., "UNCERTAIN": .5}[r[mode]] for r in selected])
                    result = metrics(y, mapped, .25, .75)
                    result["brier"] = float(np.mean((p-y)**2)) if len(y) else None
                    rows.append({"scope": scope, "method": method, "seed": seed, "mode": mode, "all_episode_n": len(full), "unknown_n": sum(r["y"] < 0 for r in full), "evaluation": "F_FROZEN_NO_TRAINING_OR_RECALIBRATION", **result})
        for method in ("always_PASSABLE", "always_BLOCKED", "E0", "E1", "E2", "E0_time_corrected", "E1_time_corrected", "E2_time_corrected"):
            rows.append({"scope": scope, "method": method, "seed": "frozen_rule", "mode": "rule", "all_episode_n": len(eps), "unknown_n": sum(e["y"] < 0 for e in eps), "evaluation": "F_FROZEN_RULE_SAME_PROBE_WINDOW", **baseline_metrics(eps, method)})
    csvwrite(output / "F_FROZEN_PREDICTIONS.csv", predictions)
    csvwrite(output / "F_FROZEN_EVALUATION.csv", rows)
    csvwrite(REPORT / "F_FROZEN_EVALUATION.csv", rows)
    dump(output / "F_FROZEN_PROVENANCE.json", {"assignments": assignments, "episode_count": len(supplements), "label_counts": {label: sum(e["label"] == label for e in supplements) for label in sorted({e["label"] for e in supplements})}, "unknown_in_metrics": False, "fit_called": False, "model_provenance": provenance, "threshold_source": "Phase-A validation metrics only; unchanged", "validity_note": "New seeds are independent executions; known family was held out from fitting. Prior E family performance was already observed, so this is not a newly blinded family selection. Screening is not confirmation."})
    return {"F_episode_count": len(supplements), "prediction_rows": len(predictions), "metric_rows": len(rows), "labels": {label: sum(e["label"] == label for e in supplements) for label in sorted({e["label"] for e in supplements})}}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model-root", type=Path, default=OUT / "phase_a_valid")
    parser.add_argument("--e-manifest", type=Path, default=OUT / "dataset/manifest.json")
    parser.add_argument("--f-manifest", type=Path, default=OUT / "dataset_phase_c/manifest.json")
    parser.add_argument("--output", type=Path, default=OUT / "frozen_evaluation")
    parser.add_argument("--verify-only", action="store_true")
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    e_manifest = load(args.e_manifest)
    assert sha(args.e_manifest) == load(args.model_root / "frozen_config.json")["manifest_sha256"], "E manifest differs from frozen training provenance"
    verified = replay(args.model_root, e_manifest, args.output)
    result = {"replay_status": verified["status"], "replay_count": verified["prediction_count"], "max_probability_error": verified["max_absolute_probability_error"]}
    if not args.verify_only:
        result.update(evaluate_f(args.model_root, e_manifest, load(args.f_manifest), args.output))
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
